// Generates supabase/seed/room_bots.sql: the fandom rooms, their bots and
// the guest bots (migration 20261125002500_room_bots.sql must be applied).
//   node supabase/seed/bots/index.mjs
//
// A fandom entry:
//   fandom: catalogue id ("anime-1"), bot: [username, display name],
//   tier: 1..3 (how many guest bots may visit at once),
//   room: [name, description], greet/topics/addressed: lines ({name}, {room}),
//   faq: [[keywords], answer, spoiler?] — every keyword must appear in the
//        question (lower case, ё as е; stems match longer words),
//   quiz: [question, accepted answer, ...more accepted answers].
// English: en-*.mjs, keyed by catalogue id, with the same fields (quizzes in
// the same order: accepted answers are merged, so either language counts).
// Ids are derived from names (md5), so running the seed again updates in place.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import anime from "./anime.mjs";
import cinema from "./cinema.mjs";
import games from "./games.mjs";
import more from "./more.mjs";
import { guests, lines, linesEn } from "./guests.mjs";
import enAnime from "./en-anime.mjs";
import enCinema from "./en-cinema.mjs";
import enGames from "./en-games.mjs";
import enMore from "./en-more.mjs";

export const rooms = [...cinema, ...anime, ...games, ...more];
export const english = { ...enAnime, ...enCinema, ...enGames, ...enMore };
const here = path.dirname(fileURLToPath(import.meta.url));
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const arr = (list) => "array[" + list.map(q).join(",") + "]::text[]";
const norm = (s) => String(s).toLowerCase().replace(/ё/g, "е").replace(/[^\p{L}\p{N}]+/gu, " ").trim();
const botId = (username) => `md5('katsodi-bot:' || ${q(username)})::uuid`;
const roomId = (fandom) => `md5('katsodi-room:' || ${q(fandom)})::uuid`;
const arts = ["orbit", "wave", "moon", "sun"];

export function check() {
  const problems = [];
  const users = new Set();
  const fandoms = new Set();
  for (const [username] of [...guests, ...rooms.map((r) => r.bot)]) {
    if (!/^[a-z][a-z0-9_]{2,23}$/.test(username)) problems.push(`bad username ${username}`);
    if (users.has(username)) problems.push(`duplicate username ${username}`);
    users.add(username);
  }
  for (const room of rooms) {
    if (fandoms.has(room.fandom)) problems.push(`duplicate fandom ${room.fandom}`);
    fandoms.add(room.fandom);
    const [name, description] = room.room;
    if (name.length < 3 || name.length > 80) problems.push(`room name length ${name}`);
    if (description.length > 500) problems.push(`description ${name}`);
    if (!(room.tier >= 1 && room.tier <= 3)) problems.push(`tier ${name}`);
    for (const [keywords, answer] of room.faq) {
      if (!keywords.length || keywords.length > 6) problems.push(`keywords ${name}`);
      for (const k of keywords) if (norm(k) !== k.toLowerCase().replace(/ё/g, "е")) problems.push(`keyword "${k}" in ${name} is not normalised`);
      if (answer.length > 1500) problems.push(`answer ${name}`);
    }
    for (const [question, ...answers] of room.quiz) if (!question || !answers.length || answers.length > 8) problems.push(`quiz ${name}`);
    if (!room.greet?.length || !room.quiz?.length || !room.faq?.length) problems.push(`content missing ${name}`);
    const en = english[room.fandom];
    if (!en) problems.push(`no English for ${name}`);
    else {
      if (!en.greet?.length || !en.faq?.length || !en.topics?.length) problems.push(`English content missing ${name}`);
      if (en.quiz.length !== room.quiz.length) problems.push(`English quiz of ${name} does not line up`);
      for (const [keywords, answer] of en.faq) {
        if (!keywords.length || keywords.length > 6) problems.push(`English keywords ${name}`);
        for (const k of keywords) if (norm(k) !== k.toLowerCase()) problems.push(`English keyword "${k}" in ${name} is not normalised`);
        if (answer.length > 1500) problems.push(`English answer ${name}`);
      }
    }
  }
  return problems;
}

export function sql() {
  const out = [];
  out.push("-- Generated by supabase/seed/bots/index.mjs; do not edit by hand.");
  out.push("-- Needs migration 20261125002500_room_bots.sql. Run in the Supabase SQL Editor.");
  out.push("begin;");
  // Bot accounts: no password, an .invalid address; they never sign in.
  const all = [...guests, ...rooms.map((r) => r.bot)];
  out.push("insert into auth.users (instance_id, id, aud, role, email, encrypted_password, raw_app_meta_data, raw_user_meta_data,");
  out.push("  created_at, updated_at, confirmation_token, recovery_token, email_change_token_new, email_change) values");
  out.push(all.map(([u]) => `  ('00000000-0000-0000-0000-000000000000', ${botId(u)}, 'authenticated', 'authenticated', ${q(u + "@bots.katsodi.invalid")}, '', '{"provider":"bot","providers":["bot"]}', '{}', now(), now(), '', '', '', '')`).join(",\n"));
  out.push("on conflict (id) do nothing;");
  for (const [u, display] of all)
    out.push(`update public.profiles set username = ${q(u)}, display_name = ${q(display)}, is_bot = true, onboarding_completed = true, bio = ${q(
      rooms.find((r) => r.bot[0] === u)
        ? `Бот комнаты «${rooms.find((r) => r.bot[0] === u).room[0]}» 🤖 Отвечает на вопросы о фандоме, проводит викторины (!quiz) и прячет спойлеры. / The room's bot: answers fandom questions, runs quizzes and hides spoilers.`
        : "Бот-собеседник Katsodi 🤖 Заглядывает в комнаты фандомов, когда там есть люди, и любит поболтать. / A Katsodi chat bot: drops into fandom rooms when people are there.",
    )} where id = ${botId(u)};`);
  out.push(`insert into public.bot_guests(bot_id) values ${guests.map(([u]) => `(${botId(u)})`).join(", ")} on conflict do nothing;`);
  // Rooms, owned by their fandom bot; resident: never cleaned up.
  rooms.forEach((room, i) => {
    const [name, description] = room.room;
    out.push(`insert into public.rooms(id, owner_id, name, description, format, visibility, url, art, fandom_id, resident)
  values (${roomId(room.fandom)}, ${botId(room.bot[0])}, ${q(name)}, ${q(description)}, 'video', 'public', '', '${arts[i % 4]}', ${q(room.fandom)}, true)
  on conflict (id) do update set name = excluded.name, description = excluded.description, resident = true, closed_at = null;`);
    out.push(`insert into public.room_bots(room_id, fandom_bot, tier) values (${roomId(room.fandom)}, ${botId(room.bot[0])}, ${room.tier})
  on conflict (room_id) do update set fandom_bot = excluded.fandom_bot, tier = excluded.tier;`);
  });
  // Content is replaced as a whole on every run.
  out.push(`delete from public.bot_faq where room_id in (select room_id from public.room_bots);`);
  out.push(`delete from public.bot_quiz_state where room_id in (select room_id from public.room_bots);`);
  out.push(`delete from public.bot_quiz where room_id in (select room_id from public.room_bots);`);
  out.push(`delete from public.bot_lines;`);
  for (const room of rooms) {
    const id = roomId(room.fandom);
    const versions = [["ru", room, english[room.fandom]], ["en", english[room.fandom], room]];
    for (const [lang, content, other] of versions) {
      for (const [keywords, answer, spoiler] of content.faq)
        out.push(`insert into public.bot_faq(room_id, lang, keywords, answer, spoiler) values (${id}, '${lang}', ${arr(keywords.map((k) => k.toLowerCase().replace(/ё/g, "е")))}, ${q(answer)}, ${spoiler ? "true" : "false"});`);
      content.quiz.forEach(([question, ...answers], i) => {
        // The other language's answers count too (shown: this language's first).
        const accepted = [...new Set([...answers, ...other.quiz[i].slice(1)])].slice(0, 12);
        out.push(`insert into public.bot_quiz(room_id, lang, question, answers) values (${id}, '${lang}', ${q(question)}, ${arr(accepted)});`);
      });
      for (const kind of ["greet", "topic", "addressed"])
        for (const body of content[kind === "topic" ? "topics" : kind] || [])
          out.push(`insert into public.bot_lines(room_id, lang, kind, body) values (${id}, '${lang}', '${kind}', ${q(body)});`);
    }
  }
  for (const [lang, set] of [["ru", lines], ["en", linesEn]])
    for (const [kind, list] of Object.entries(set))
      for (const body of list) out.push(`insert into public.bot_lines(room_id, lang, kind, body) values (null, '${lang}', '${kind}', ${q(body)});`);
  out.push("commit;");
  return out.join("\n") + "\n";
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const problems = check();
  if (problems.length) {
    console.error(problems.join("\n"));
    process.exit(1);
  }
  const file = path.join(here, "..", "room_bots.sql");
  fs.writeFileSync(file, sql());
  console.log(`${rooms.length} rooms, ${rooms.length + guests.length} bots -> ${path.relative(process.cwd(), file)}`);
}
