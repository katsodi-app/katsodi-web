// Generates public/offline/index.html, the page the service worker shows
// when a navigation fails. Its texts come from the `desktop` section of
// src/lib/i18n.ts and its colours from src/app/signal.css, so there is one
// source for both; tests/unit/platform.test.ts fails when the committed file
// is out of date. Run: npm run offline:build
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { build } from "esbuild";

export async function offlinePage(root = process.cwd()) {
  const temporary = path.join(root, ".next-offline-i18n.mjs");
  await build({
    entryPoints: [path.join(root, "src/lib/i18n.ts")],
    outfile: temporary,
    bundle: true,
    format: "esm",
    platform: "neutral",
    logLevel: "silent",
  });
  let messages;
  try {
    ({ messages } = await import(
      pathToFileURL(temporary).href + "?" + Date.now()
    ));
  } finally {
    await rm(temporary, { force: true });
  }
  const keys = [
    "offlineTitleOffline",
    "offlineBodyOffline",
    "offlineLocalNote",
    "retry",
  ];
  const strings = Object.fromEntries(
    ["ru", "en"].map((locale) => [
      locale,
      Object.fromEntries(keys.map((key) => [key, messages[locale].desktop[key]])),
    ]),
  );
  const signal = (
    await readFile(path.join(root, "src/app/signal.css"), "utf8")
  ).replaceAll("\r\n", "\n");
  const start = signal.indexOf(':root,\n[data-theme="obsidian"] {');
  const end = signal.indexOf(":root,\n[data-theme] {");
  if (start < 0 || end < start)
    throw new Error("The palettes were not found in src/app/signal.css.");
  const palettes = signal.slice(start, end).trim();
  const logo = (await readFile(path.join(root, "src/app/icon.svg"), "utf8"))
    .trim()
    .replace("<svg ", '<svg class="logo" width="56" height="56" aria-hidden="true" ');
  const en = strings.en;
  return `<!doctype html>
<!-- Generated by scripts/build-offline-page.mjs. Do not edit by hand. -->
<html lang="en" data-theme="obsidian">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>${en.offlineTitleOffline} · Katsodi</title>
<style>
${palettes}
@font-face{font-family:"Manrope";font-weight:200 800;font-display:swap;src:url("/fonts/manrope/manrope-cyrillic.woff2") format("woff2");unicode-range:U+0301,U+0400-045F,U+0490-0491,U+04B0-04B1,U+2116}
@font-face{font-family:"Manrope";font-weight:200 800;font-display:swap;src:url("/fonts/manrope/manrope-latin.woff2") format("woff2");unicode-range:U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD}
*{box-sizing:border-box}
html,body{height:100%;margin:0}
body{display:grid;place-items:center;padding:24px 16px;background:var(--background);color:var(--foreground);font-family:"Manrope",system-ui,sans-serif;font-size:15px;line-height:1.55}
main{width:min(100%,460px)}
.logo{display:block;margin-bottom:22px}
.eyebrow{margin:0 0 6px;font-size:11px;letter-spacing:.14em;text-transform:uppercase;color:var(--accent)}
h1{margin:0;font-size:clamp(22px,4vw,30px);line-height:1.15;letter-spacing:-.03em}
.lead{margin:12px 0 0;color:var(--muted-foreground)}
.note{margin:18px 0 0;padding:12px 14px;border:1px solid var(--border);border-radius:10px;background:var(--surface);font-size:13px;color:var(--muted-foreground)}
button{min-height:44px;margin-top:22px;padding:0 20px;border:0;border-radius:10px;background:var(--primary);color:var(--primary-foreground);font:inherit;font-weight:700;cursor:pointer}
:focus-visible{outline:2px solid var(--focus-ring);outline-offset:2px}
</style>
</head>
<body>
<main>
${logo}
<p class="eyebrow">Katsodi</p>
<h1 data-t="offlineTitleOffline">${en.offlineTitleOffline}</h1>
<p class="lead" data-t="offlineBodyOffline">${en.offlineBodyOffline}</p>
<p class="note" data-t="offlineLocalNote">${en.offlineLocalNote}</p>
<button type="button" id="retry" data-t="retry">${en.retry}</button>
</main>
<script>
(function(){
var strings=${JSON.stringify(strings)};
var locale="en",theme="obsidian";
try{
var l=localStorage.getItem("katsodi.locale");
locale=l==="ru"||l==="en"?l:(navigator.language||"").toLowerCase().indexOf("ru")===0?"ru":"en";
var t=localStorage.getItem("katsodi.theme");
if(t==="system")t=matchMedia("(prefers-color-scheme: light)").matches?"paper":"obsidian";
if(["obsidian","ember","aurora","violet","paper"].indexOf(t)>=0)theme=t;
}catch(e){}
var root=document.documentElement;root.lang=locale;root.dataset.theme=theme;
var nodes=document.querySelectorAll("[data-t]");
for(var i=0;i<nodes.length;i++)nodes[i].textContent=strings[locale][nodes[i].getAttribute("data-t")];
document.title=strings[locale].offlineTitleOffline+" · Katsodi";
document.getElementById("retry").addEventListener("click",function(){location.reload();});
addEventListener("online",function(){location.reload();});
})();
</script>
</body>
</html>
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await mkdir("public/offline", { recursive: true });
  await writeFile("public/offline/index.html", await offlinePage());
  console.log("Wrote public/offline/index.html.");
}
