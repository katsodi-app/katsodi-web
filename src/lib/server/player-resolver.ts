import {
  knownPlayer,
  findPlayerFrames,
  type PlayerResolution,
} from "../player";
import { discoveryPlan, type DiscoveryPlan } from "../player-recipes";
import { genericPlayer } from "./generic-player-resolver";
import { vkApiPlayer } from "./vk-video";
import { vkVideoId } from "../providers";
const cache = new Map<string, { until: number; result: PlayerResolution }>();
const pending = new Map<string, Promise<PlayerResolution>>();
class SourceFailure extends Error {
  constructor(readonly reason: "blocked" | "unavailable") {
    super(reason);
  }
}
async function publicDocument(
  url: string,
  maxBytes: number,
  mime: "html" | "json",
  deadline: number,
) {
  if (Date.now() >= deadline) throw new SourceFailure("unavailable");
  // All URLs are generated by reviewed recipes or approvedFrame. Never replay
  // browser cookies, user sessions, Origin/Referer spoofing or arbitrary redirects.
  const response = await fetch(url, {
    redirect: "manual",
    cache: "no-store",
    signal: AbortSignal.timeout(
      Math.max(1, Math.min(8000, deadline - Date.now())),
    ),
    headers: { Accept: mime === "html" ? "text/html" : "application/json" },
  });
  const contentType = response.headers.get("content-type")?.toLowerCase() || "";
  if (
    !response.ok ||
    !contentType.includes(mime === "html" ? "text/html" : "application/json")
  ) {
    await response.body?.cancel();
    throw new SourceFailure(
      [401, 403].includes(response.status) ? "blocked" : "unavailable",
    );
  }
  const reader = response.body?.getReader();
  if (!reader) throw new SourceFailure("unavailable");
  const chunks: Uint8Array[] = [];
  let length = 0;
  try {
    while (true) {
      const part = await reader.read();
      if (part.done) break;
      length += part.value.byteLength;
      if (length > maxBytes) throw new SourceFailure("unavailable");
      chunks.push(part.value);
    }
  } finally {
    await reader.cancel();
  }
  return {
    body: Buffer.concat(chunks).toString("utf8"),
    headers: response.headers,
  };
}
function blocksEmbedding(headers: Headers) {
  if (headers.has("x-frame-options")) return true;
  const policy = headers
    .get("content-security-policy")
    ?.match(/(?:^|;)\s*frame-ancestors\s+([^;]+)/i)?.[1]
    ?.trim();
  return !!policy && policy !== "*";
}
async function discover(plan: DiscoveryPlan): Promise<PlayerResolution> {
  const deadline = Date.now() + 15000;
  try {
    const page = await publicDocument(
      plan.page,
      2 * 1024 * 1024,
      "html",
      deadline,
    );
    const candidates = findPlayerFrames(page.body, plan.page);
    let blocked = false;
    for (const frame of candidates.slice(0, 3)) {
      try {
        const result = await publicDocument(
          frame,
          512 * 1024,
          "html",
          deadline,
        );
        if (blocksEmbedding(result.headers)) {
          blocked = true;
          continue;
        }
        return {
          kind: "iframe",
          src: frame,
          provider: plan.provider,
          sync: false,
        };
      } catch (error) {
        if (error instanceof SourceFailure && error.reason === "blocked")
          blocked = true;
      }
    }
    return {
      kind: "external",
      reason: blocked
        ? "blocked"
        : candidates.length
          ? "unavailable"
          : "notFound",
      sync: false,
    };
  } catch (error) {
    return {
      kind: "external",
      reason: error instanceof SourceFailure ? error.reason : "unavailable",
      sync: false,
    };
  }
}
export async function resolvePlayer(input: string): Promise<PlayerResolution> {
  const direct = knownPlayer(input);
  if (direct.kind !== "discover") return direct;
  const plan = discoveryPlan(input);
  const vk = vkVideoId(new URL(input));
  const key = vk
      ? `vk-api:${vk}`
      : plan
        ? `${plan.adapter}:${plan.page}`
        : `generic-v1:${input}`,
    cached = cache.get(key);
  if (cached && cached.until > Date.now()) return cached.result;
  const underway = pending.get(key);
  if (underway) return underway;
  if (pending.size >= 4)
    return { kind: "external", reason: "unavailable", sync: false };
  const lookup = vk
    ? vkApiPlayer(input)
    : plan
      ? discover(plan)
      : genericPlayer(input);
  pending.set(key, lookup);
  try {
    const result = await lookup;
    if (cache.size >= 128) cache.delete(cache.keys().next().value!);
    cache.set(key, {
      until: Date.now() + (result.kind === "iframe" ? 300000 : 30000),
      result,
    });
    return result;
  } finally {
    pending.delete(key);
  }
}
