/** Preserve stable section anchors and versions; fail loudly on missing translations. */
export function russianLegalDoc(doc: LegalDoc): LegalDoc {
  const translation = translations[doc.slug];
  return {
    ...doc,
    title: translation.title,
    summary: translation.summary,
    sections: doc.sections.map(({ id }) => {
      const section = translation.sections[id];
      if (!section)
        throw new Error(`Missing Russian legal section: ${doc.slug}/${id}`);
      return { id, ...section };
    }),
  };
}
